import {build,transform} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const options={absWorkingDir:fileURLToPath(new URL('.',import.meta.url)),bundle:true,minify:true,format:'esm',target:['es2022'],tsconfigRaw:{},legalComments:'none'};
await build({...options,entryPoints:['src/app.mjs'],outfile:'dist/app-v3.mjs',external:['./report-v2.mjs'],define:{__BIZTRACK_PORTABLE__:'false'}});
await build({...options,entryPoints:['dist/report.mjs'],outfile:'dist/report-v2.mjs'});
const css=await transform(await readFile('src/styles.css','utf8'),{loader:'css',minify:true,target:['es2022']});await writeFile('dist/styles-v3.css',css.code);
const theme=await readFile('dist/theme.js','utf8'),hash=createHash('sha256').update(theme).digest('base64');
const html=(await readFile('src/index.html','utf8')).replace('__THEME_CSP__',`'sha256-${hash}'`).replace('<!-- BIZTRACK_THEME -->',()=>`<script>${theme}</script>`);await writeFile('dist/index.html',html);
console.log('Built compact BizTrack assets with a deferred PDF tool and CSP-authorized theme.');
